def _system_prompt() -> str:  # 原 L57-66
    """设置页（general.system_prompt）优先——管理员在那里改的就是最终生效的；没填才用出厂默认。"""
    try:
        from settings_mgr import load_settings
        sp = (load_settings().get("general", {}) or {}).get("system_prompt", "")
        if sp and sp.strip():
            return sp
    except Exception:
        pass
    return _DEFAULT_PROMPT
